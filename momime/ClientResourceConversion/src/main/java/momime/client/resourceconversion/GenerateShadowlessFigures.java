package momime.client.resourceconversion;

import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.net.URL;
import java.util.HashMap;
import java.util.Map;
import java.util.stream.Collectors;

import javax.imageio.ImageIO;
import javax.xml.XMLConstants;
import javax.xml.validation.Schema;
import javax.xml.validation.SchemaFactory;

import org.w3c.dom.bootstrap.DOMImplementationRegistry;

import jakarta.xml.bind.JAXBContext;
import jakarta.xml.bind.Marshaller;
import jakarta.xml.bind.Unmarshaller;
import momime.common.database.Animation;
import momime.common.database.AnimationFrame;
import momime.common.database.CommonDatabaseConstants;
import momime.common.database.CommonXsdResourceResolver;
import momime.common.database.MomDatabase;
import momime.common.database.Unit;
import momime.common.database.UnitCombatAction;
import momime.common.database.UnitCombatImage;

/**
 * The original shadowless images were generated by FiguresExtract, direct from the .LBX files, not from the existing .pngs.
 * That means it won't work for Simbey's upscaled combat figures.  So need to write one specially to generate shadowless images from those.
 */
public final class GenerateShadowlessFigures
{
	/** Location of XML to read/update*/
	private final static File XML_LOCATION = new File ("W:\\EclipseHome\\SF\\MoMIME\\Server\\src\\external\\resources\\momime.server.database\\Original Master of Magic 1.31 rules.momime.xml");
	
	/** Root location where the image names are relative to */
	private final static File ROOT_LOCATION = new File ("W:\\EclipseHome\\SF\\MoMIME\\Client\\src\\main\\resources");
	
	/**
	 * @param shadowedImageName Shadowed image name from XML
	 * @param processedImages Map of already processed images
	 * @return filename without shadows if there are any shadows, or null if the image has no shadow pixels (in other words, what to write into the UP slot in the XML)
	 * @throws Exception If there is a problem
	 */
	private final String processImage (final String shadowedImageName, final Map<String, String> processedImages) throws Exception
	{
		// First see if its already in the map
		String shadowlessImageName;
		if (processedImages.containsKey (shadowedImageName))
			shadowlessImageName = processedImages.get (shadowedImageName);
		else
		{
			// For some reason, images fail to read using the full path, but work fine when read as classpath resources
			try (final InputStream src = getClass ().getResourceAsStream (shadowedImageName))
			{
				final BufferedImage image = ImageIO.read (src);
				
				// Remove the shadows from the image
				boolean shadowRemoved = false;
				for (int y = 0; y < image.getHeight (); y++)
					for (int x = 0; x < image.getWidth (); x++)
					{
						final int c = image.getRGB (x, y);
						if ((c == 0x80000000) || (c == 0x80080404))		// 2nd one is only used on doom bats
						{
							image.setRGB (x, y, 0);
							shadowRemoved = true;
						}
					}
				
				if (shadowRemoved)
				{
					System.out.println (shadowedImageName + " processed and generated shadowless image from");
					
					shadowlessImageName = shadowedImageName.substring (0, shadowedImageName.length () - 4) + "-shadowless.png";
					final File shadowlessImageFile = new File (ROOT_LOCATION, shadowlessImageName);
					if (!ImageIO.write (image, "png", shadowlessImageFile))
						throw new IOException ("Failed to save " + shadowlessImageFile);
				}
				else
				{
					System.out.println (shadowedImageName + " has no shadows");
					
					shadowlessImageName = null;
				}
				
				processedImages.put (shadowedImageName, shadowlessImageName);
			}
		}
		
		return shadowlessImageName;
	}
	
	/**
	 * @throws Exception If there is a problem
	 */
	public final void run () throws Exception
	{
		// Read XML
		final URL xsdResource = getClass ().getResource (CommonDatabaseConstants.COMMON_XSD_LOCATION);

		final SchemaFactory schemaFactory = SchemaFactory.newInstance (XMLConstants.W3C_XML_SCHEMA_NS_URI);
		schemaFactory.setResourceResolver (new CommonXsdResourceResolver (DOMImplementationRegistry.newInstance ()));
		
		final Schema schema = schemaFactory.newSchema (xsdResource);

		final Unmarshaller unmarshaller = JAXBContext.newInstance (MomDatabase.class).createUnmarshaller ();		
		unmarshaller.setSchema (schema);

		final MomDatabase db = (MomDatabase) unmarshaller.unmarshal (XML_LOCATION);
		final Map<String, Animation> animationsMap = db.getAnimation ().stream ().collect (Collectors.toMap (a -> a.getAnimationID (), a -> a));
		
		// Make a map of already processed images, since they get repeated a lot especially once we get to animations
		// Key = filename with shadows, value = filename without shadows if there are any shadows, or null if the image has no shadow pixels
		final Map<String, String> processedImages = new HashMap<String, String> ();
		
		for (final Unit unit : db.getUnit ())
			for (final UnitCombatAction action : unit.getUnitCombatAction ())
				for (final UnitCombatImage unitImage : action.getUnitCombatImage ())
				{
					// Static images
					if (unitImage.getUnitCombatImageFileUP () != null)
						unitImage.setUnitCombatShadowlessImageFileUP (processImage (unitImage.getUnitCombatImageFileUP (), processedImages));
					
					// Animations
					if ((unitImage.getUnitCombatAnimation () != null) && (unitImage.getUnitCombatAnimationUP () != null))
					{
						final Animation normalAnim = animationsMap.get (unitImage.getUnitCombatAnimation ());
						final Animation upscaledAnim = animationsMap.get (unitImage.getUnitCombatAnimationUP ());
						
						if (normalAnim.getFrame ().size () != upscaledAnim.getFrame ().size ())
							throw new Exception ("Unit " + unit.getUnitID () + " references anims " + unitImage.getUnitCombatAnimation () + " and " + unitImage.getUnitCombatAnimationUP () + " which have different numbers of frames");
						
						for (int frameNo = 0; frameNo < normalAnim.getFrame ().size (); frameNo++)
						{
							final AnimationFrame normalFrame = normalAnim.getFrame ().get (frameNo);
							final AnimationFrame upscaledFrame = upscaledAnim.getFrame ().get (frameNo);
							
							upscaledFrame.setShadowlessImageFile (processImage (upscaledFrame.getImageFile (), processedImages));
							upscaledFrame.setShadowImageFile (normalFrame.getShadowImageFile ());
						}
					}
				}

		// Save out the updated XML
		final Marshaller marshaller = JAXBContext.newInstance (MomDatabase.class).createMarshaller ();		
		marshaller.setSchema (schema);
		marshaller.setProperty (Marshaller.JAXB_FORMATTED_OUTPUT, true);
		marshaller.marshal (db, XML_LOCATION);
		
		System.out.print ("All done!");
	}
	
	/**
	 * @param args Command line arguments, ignored
	 */
	public final static void main (final String [] args)
	{
		try
		{
			new GenerateShadowlessFigures ().run ();
		}
		catch (final Exception e)
		{
			e.printStackTrace ();
		}
	}
}